package com.acea.backend.domain.enums;

/**
 * Assessment types supported by the ACEA Assessment Engine.
 */
public enum AssessmentType {
    /** Aptitude test measuring logical, numerical, verbal, analytical, and programming skills. */
    APTITUDE,
    /** Personality assessment based on the Big Five (OCEAN) model. */
    PERSONALITY,
    /** Interest assessment based on Holland's RIASEC model. */
    INTEREST
}
